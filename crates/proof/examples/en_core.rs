//! Regenerate `data/en-core.txt`, the English core word list (see the crate README).
//!
//! ```sh
//! cargo run -p craft-proof --example en_core -- <craft-i18n>/language-data/en-us/en-us.dic <count> <out> <book.txt>...
//! ```
//!
//! Every word in the list comes from the public-domain Moby Hyphenator II list (`en-us.dic`).
//! The books (public-domain Project Gutenberg plain-text files) only rank those words: a word is
//! counted where it is written in lower case (so names, which are capitalized, rank low), must
//! appear in at least [`MIN_BOOKS`] of the books, and the `<count>` most frequent are written,
//! sorted. No other word list or dictionary is read.
//!
//! `data/en-core.txt` was made with `<count>` 12000 (11,367 words pass [`MIN_BOOKS`]) from these
//! Project Gutenberg eBooks (`https://www.gutenberg.org/cache/epub/<n>/pg<n>.txt`, fetched
//! 2026-11-01): 11 16 35 36 43 45 55 74 76 84 98 105 113 120 135 141 158 161 174 215 219 244 345
//! 408 514 730 766 768 1023 1080 1184 1228 1260 1342 1400 1497 1661 1952 2542 2554 2600 2701 2814
//! 2852 3600 3825 4300 5230 25344 64317.

use std::collections::{HashMap, HashSet};

/// A word must occur, in lower case, in at least this many books.
const MIN_BOOKS: usize = 8;

fn main() -> Result<(), String> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let [dic, count, out, books @ ..] = args.as_slice() else {
        return Err("usage: en_core <en-us.dic> <count> <out> <book.txt>...".into());
    };
    let count: usize = count.parse().map_err(|e| format!("count: {e}"))?;
    let bytes = std::fs::read(dic).map_err(|e| format!("{dic}: {e}"))?;
    let moby = craft_proof::dict::Dictionary::from_bytes(&bytes)?;
    let moby: HashSet<&str> = moby.iter().map(|(w, _)| w).collect();
    let mut freq: HashMap<String, (u64, usize)> = HashMap::new();
    for book in books {
        let text = std::fs::read_to_string(book).map_err(|e| format!("{book}: {e}"))?;
        // The Project Gutenberg header and licence are not the book.
        let body = text.split_once("*** START OF").map_or(text.as_str(), |(_, b)| b);
        let body = body.split_once("*** END OF").map_or(body, |(b, _)| b);
        let mut seen: HashSet<&str> = HashSet::new();
        for w in body.split(|c: char| !(c.is_ascii_alphabetic() || c == '\'')).map(|w| w.trim_matches('\'')) {
            if w.len() < 2 || !w.bytes().all(|b| b.is_ascii_lowercase() || b == b'\'') || !moby.contains(w) {
                continue;
            }
            let e = freq.entry(w.to_string()).or_default();
            e.0 += 1;
            if seen.insert(w) {
                e.1 += 1;
            }
        }
    }
    let mut ranked: Vec<(String, u64)> = freq.into_iter().filter(|(_, (_, b))| *b >= MIN_BOOKS).map(|(w, (n, _))| (w, n)).collect();
    ranked.sort_by(|a, b| b.1.cmp(&a.1).then_with(|| a.0.cmp(&b.0)));
    ranked.truncate(count);
    let mut words: Vec<String> = ranked.into_iter().map(|(w, _)| w).collect();
    words.sort();
    let mut o = String::from(
        "# English core word list: the built-in fallback when neither the embedded Language data nor a\n\
         # system Hunspell English dictionary is available (see crates/proof/README.md).\n\
         # Public domain: every word is from the Moby Hyphenator II list by Grady Ward (Project\n\
         # Gutenberg eBook #3204), ranked by frequency in public-domain Project Gutenberg books.\n\
         # Generated by `cargo run -p craft-proof --example en_core`. Do not edit by hand.\n",
    );
    for w in &words {
        o.push_str(w);
        o.push('\n');
    }
    std::fs::write(out, o).map_err(|e| format!("{out}: {e}"))?;
    eprintln!("{} words", words.len());
    Ok(())
}

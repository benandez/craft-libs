//! English spelling never goes unchecked. Its words come from the first of these that is there:
//!
//! 1. **Embedded**: the Moby word list embedded from craft-i18n at build time (`CRAFT_I18N_DIR`,
//!    see `build.rs`). When it is there, nothing in this module is used.
//! 2. **System Hunspell**: an English Hunspell `.aff`/`.dic` pair found by [`crate::hunspell`]
//!    (the dictionaries folder first, then the system locations; none on the web). The run's
//!    English is tried first (`en_US`, `en_GB`, `en_CA`…), then the other Englishes: a full
//!    dictionary in the other spelling marks fewer right words than the core list.
//! 3. **Core list**: [`CORE_LIST`], about 11,000 common words compiled into the crate (with the
//!    usual inflections). A word it doesn't know is marked only when it is a near miss of a
//!    common word (`teh`, `recieve`, `definately`); any other word it doesn't know (a rare word, a
//!    name, a term) is taken as correct, as it may well be right.
//!
//! A Hunspell dictionary that is there but can't be read (unsupported encoding, too large, a
//! parse error, no words) is skipped for the core list, and its reason is reported by
//! [`crate::dictionary_load_error`]. Non-English text is never checked against any of these.

use std::path::PathBuf;
use std::sync::{Arc, OnceLock, RwLock};

use crate::affix::AffixDict;
use crate::{Options, ProofLang};

/// The English core word list (`data/en-core.txt`): the most common words of the public-domain
/// Moby Hyphenator II list by Grady Ward, ranked by their frequency in public-domain Project
/// Gutenberg books (generated by `examples/en_core.rs`). One lowercase word per line, `#`
/// comments.
const CORE_LIST: &str = include_str!("../data/en-core.txt");

/// Where English spelling comes from now ([`crate::english_source`]).
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum EnglishSource {
    /// The Moby word list embedded from craft-i18n at build time.
    Embedded,
    /// An English Hunspell dictionary from the dictionaries folder or the system: its `.dic` file.
    Hunspell(PathBuf),
    /// The core word list built into the crate: only near misses of common words are marked.
    CoreList,
}

/// The words of [`CORE_LIST`].
fn core() -> &'static std::collections::HashSet<&'static str> {
    static C: OnceLock<std::collections::HashSet<&'static str>> = OnceLock::new();
    C.get_or_init(|| CORE_LIST.lines().map(str::trim).filter(|l| !l.is_empty() && !l.starts_with('#')).collect())
}

/// Is `w` (lower case) a word of the core list?
pub(crate) fn core_contains(w: &str) -> bool {
    core().contains(w)
}

/// Hunspell file names to look for, the run's English first.
fn names(lang: ProofLang) -> &'static [&'static str] {
    match lang {
        ProofLang::EnGb => &["en_GB", "en-GB", "en_AU", "en_NZ", "en_IE", "en_ZA", "en_IN", "en", "en_CA", "en_US", "en-US"],
        ProofLang::EnCa => &["en_CA", "en-CA", "en", "en_US", "en-US", "en_GB", "en-GB"],
        _ => &["en_US", "en-US", "en", "en_CA", "en_GB", "en-GB", "en_AU"],
    }
}

/// The slot of each English in [`HUNSPELL`].
fn slot(lang: ProofLang) -> usize {
    match lang {
        ProofLang::EnGb => 1,
        ProofLang::EnCa => 2,
        _ => 0,
    }
}

/// A loaded Hunspell dictionary and its `.dic` file; `None` when none could be loaded.
type Loaded = Option<(Arc<AffixDict>, PathBuf)>;

/// Per English (see [`slot`]): `None` until first use, then what was found.
static HUNSPELL: RwLock<[Option<Loaded>; 3]> = RwLock::new([None, None, None]);

/// Why the embedded word list failed to decode, if it did.
static EMBEDDED_ERROR: OnceLock<String> = OnceLock::new();

/// Remember that the embedded word list is there but failed to decode (English then uses the
/// next source).
pub(crate) fn note_embedded_error(e: String) {
    log::error!("embedded English word list: {e}; English spelling falls back to Hunspell or the core word list");
    let _ = EMBEDDED_ERROR.set(e);
}

/// The English Hunspell dictionary for `lang` (read on first use).
fn hunspell(lang: ProofLang) -> Loaded {
    let i = slot(lang);
    if let Some(Some(found)) = HUNSPELL.read().unwrap_or_else(std::sync::PoisonError::into_inner).get(i) {
        return found.clone();
    }
    let loaded = load(lang);
    let mut slots = HUNSPELL.write().unwrap_or_else(std::sync::PoisonError::into_inner);
    // Another thread may have filled it meanwhile: that one wins.
    match slots.get_mut(i) {
        Some(s) => s.get_or_insert(loaded).clone(),
        None => loaded,
    }
}

/// The key load errors of `lang` are kept under ([`crate::hunspell::load_error`]).
fn key(lang: ProofLang) -> &'static str {
    names(lang).first().copied().unwrap_or("en_US")
}

fn load(lang: ProofLang) -> Loaded {
    let key = key(lang);
    let Some((aff, dic)) = crate::hunspell::find(names(lang)) else {
        crate::hunspell::clear_load_error(key);
        log::info!("English spelling: no Hunspell English dictionary installed; using the core word list");
        return None;
    };
    let loaded = crate::hunspell::load(&aff, &dic).and_then(|d| if d.is_empty() { Err(format!("{}: no words", dic.display())) } else { Ok(d) });
    match crate::hunspell::note_load(key, &dic, loaded) {
        Ok(d) => Some((Arc::new(d), dic)),
        Err(e) => {
            log::warn!("English spelling: {e}; using the core word list");
            None
        }
    }
}

/// Forget the loaded dictionaries, so the next check looks for them again (the dictionaries
/// folder changed).
pub(crate) fn reload() {
    *HUNSPELL.write().unwrap_or_else(std::sync::PoisonError::into_inner) = [None, None, None];
}

/// Where the spelling of `lang` (an English) comes from now. Reads the Hunspell dictionary once
/// when there is no embedded data (it is cached afterwards).
pub(crate) fn source(lang: ProofLang) -> EnglishSource {
    if crate::english_data() {
        EnglishSource::Embedded
    } else {
        hunspell(lang).map_or(EnglishSource::CoreList, |(_, dic)| EnglishSource::Hunspell(dic))
    }
}

/// Why a source of `lang`'s spelling failed to load: the embedded word list, or (without it) the
/// Hunspell dictionary found for it. Reads nothing itself.
pub(crate) fn load_error(lang: ProofLang) -> Option<String> {
    if let Some(e) = EMBEDDED_ERROR.get() {
        return Some(e.clone());
    }
    if crate::english_data() {
        return None;
    }
    crate::hunspell::load_error(key(lang)).map(|(_, reason)| reason)
}

/// Is `word` spelled right in `lang` (an English) when no word list is embedded: against the
/// Hunspell dictionary, or else the core list.
pub(crate) fn is_correct(word: &str, lang: ProofLang, opts: &Options) -> bool {
    let w = word.trim_matches(|c: char| !c.is_alphanumeric() && c != '\'' && c != '’').trim_matches(['\'', '’']);
    if crate::accepted_by_options(w, opts) || !w.chars().any(|c| c.is_ascii_alphabetic()) {
        return true; // other scripts: not English
    }
    let w = w.replace('’', "'");
    match hunspell(lang) {
        Some((d, _)) => hunspell_correct(&d, &w),
        None => core_correct(&w),
    }
}

/// Against an installed English Hunspell dictionary: the word, or each part of a hyphenated one.
fn hunspell_correct(d: &AffixDict, w: &str) -> bool {
    let known = |p: &str| p.chars().count() <= 1 || d.check(p) || crate::in_user_dictionary(&p.to_lowercase());
    known(w) || (w.contains('-') && w.split('-').filter(|p| !p.is_empty()).all(known))
}

/// Against the core list: known words and their inflections are right, and so is any other word
/// that isn't a near miss of a common one ([`near_miss`]).
fn core_correct(w: &str) -> bool {
    let capitalized = w.chars().next().is_some_and(char::is_uppercase);
    let lower = w.to_lowercase();
    let ok = |p: &str| crate::known_in_core_list(p) || !near_miss(p, capitalized);
    if lower.contains('-') { crate::known_in_core_list(&lower) || lower.split('-').filter(|p| !p.is_empty()).all(ok) } else { ok(&lower) }
}

/// Is `lower` (a word the core list doesn't know) an obvious misspelling of a common word? Two
/// neighbouring letters swapped (`teh`, `Hte`, `recieved`) always is. Otherwise, for lower-case
/// words of four letters or more, one letter added, missing or changed (`definately`,
/// `ocurred`). Shorter words and capitalized ones (names) are left alone: too many right ones are
/// one letter from a common word.
fn near_miss(lower: &str, capitalized: bool) -> bool {
    let target: Vec<char> = lower.chars().collect();
    let n = target.len();
    if !(3..=40).contains(&n) {
        return false;
    }
    if core().iter().any(|c| is_swap(&target, c)) {
        return true;
    }
    if capitalized || n < 4 {
        return false;
    }
    core().iter().any(|c| {
        let m = c.chars().count();
        m + 1 >= n && m <= n + 1 && crate::damerau(&target, c) <= 1
    })
}

/// Is `b` `a` with two neighbouring letters swapped?
fn is_swap(a: &[char], b: &str) -> bool {
    if b.len() < a.len() || b.chars().count() != a.len() {
        return false;
    }
    let diff: Vec<(usize, char)> = b.chars().enumerate().filter(|&(i, c)| a.get(i) != Some(&c)).collect();
    match diff.as_slice() {
        [(i, x), (j, y)] => *j == i + 1 && a.get(*i) == Some(y) && a.get(*j) == Some(x),
        _ => false,
    }
}

/// Spelling suggestions in `lang` (an English) when no word list is embedded: from the Hunspell
/// dictionary, or else the core list.
pub(crate) fn suggest(word: &str, max: usize, lang: ProofLang) -> Vec<String> {
    match hunspell(lang) {
        Some((d, _)) => crate::cs::suggest::suggest_in(&d, word, max),
        None => core_suggest(word, max),
    }
}

/// Suggestions from the core list: by edit distance ([`crate::suggest_from`]), two swapped
/// letters first (`teh` → `the` before `tea`).
fn core_suggest(word: &str, max: usize) -> Vec<String> {
    let target: Vec<char> = word.to_lowercase().chars().collect();
    let mut out = crate::suggest_from(word, max.saturating_add(4), core().iter().copied());
    out.sort_by_key(|s| !is_swap(&target, &s.to_lowercase()));
    out.truncate(max);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn core_list_is_small_sorted_lowercase_and_has_the_common_words() {
        assert!(CORE_LIST.len() < 100 * 1024, "{} bytes", CORE_LIST.len());
        let words: Vec<&str> = CORE_LIST.lines().filter(|l| !l.starts_with('#')).collect();
        assert!(words.len() > 5_000, "{}", words.len());
        assert!(words.windows(2).all(|w| w[0] < w[1]), "sorted, no repeats");
        assert!(words.iter().all(|w| !w.is_empty() && w.chars().all(|c| c.is_ascii_lowercase() || c == '\'')));
        for w in ["the", "house", "because", "received", "definitely", "separate", "occurred", "beautiful", "people", "water"] {
            assert!(core_contains(w), "{w}");
        }
    }

    /// The core list marks obvious misspellings and leaves right words alone, inflected ones and
    /// words it doesn't know included.
    #[test]
    fn core_list_flags_near_misses_only() {
        for w in ["teh", "Teh", "hte", "recieved", "definately", "seperate", "ocurred", "becuase", "peopel", "beautifull", "watre"] {
            assert!(!core_correct(w), "{w} is marked");
        }
        for w in [
            "the",
            "The",
            "houses",
            "running",
            "looked",
            "happily",
            "kindness",
            "Received",
            "well-known",
            // Not in the list, but not a near miss of a common word either: left alone.
            "photosynthesis",
            "zxqv",
            "Nguyen",
            "Jarndyce",
            "cat",
        ] {
            assert!(core_correct(w), "{w} is not marked");
        }
        assert!(!core_correct("well-knwon"), "each part of a compound is checked");
    }

    #[test]
    fn swaps_are_two_neighbouring_letters() {
        let a: Vec<char> = "teh".chars().collect();
        assert!(is_swap(&a, "the"));
        assert!(!is_swap(&a, "teh") && !is_swap(&a, "ten") && !is_swap(&a, "thee") && !is_swap(&a, "het"));
        assert!(!is_swap(&"é".chars().collect::<Vec<_>>(), "ab"));
    }

    #[test]
    fn core_list_suggests_the_common_word() {
        assert_eq!(core_suggest("teh", 3).first().map(String::as_str), Some("the"));
        assert_eq!(core_suggest("Teh", 3).first().map(String::as_str), Some("The"));
        assert!(core_suggest("definately", 5).contains(&"definitely".to_string()));
        assert!(core_suggest("", 5).is_empty() && core_suggest("teh", 0).is_empty());
    }
}
